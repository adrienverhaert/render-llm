	RealType project_save(ScopeAny self, VarArgs argument)
	{
		IntType argument_count = argument.Size();
		VarType fn = (argument_count > IntType(0) ? argument[IntType(0)] : sVar(project_file));
		log({ /*"Saving project"*/ STR(5855), fn });
		sReal(mi3_save_guard_blocked) = false;
		if (instance_number(ID_obj_timeline) == IntType(0) && ds_list_size(idInt(sInt(lib_list), list)) == IntType(0) && file_exists_lib(fn))
		{
			IntType mi3old = json_load({ fn });
			IntType mi3had = IntType(0);
			if (ds_map_valid(mi3old))
			{
				VarType mi3tl = DsMap(mi3old).Value(/*"timelines"*/ STR(3433));
				VarType mi3tp = DsMap(mi3old).Value(/*"templates"*/ STR(3412));
				VarType mi3rs = DsMap(mi3old).Value(/*"resources"*/ STR(372));
				if (ds_list_valid(mi3tl))
					mi3had += ds_list_size((IntType)(mi3tl));
				if (ds_list_valid(mi3tp))
					mi3had += ds_list_size((IntType)(mi3tp));
				if (ds_list_valid(mi3rs))
					mi3had += ds_list_size((IntType)(mi3rs));
				ds_map_destroy(mi3old);
			}
			if (mi3had > IntType(0))
			{
				file_copy_lib(fn, fn + /*".rescue"*/ STR(5856));
				log({ /*"MI3 save guard"*/ STR(2959), /*"estado VACIO sobre un proyecto con "*/ STR(5857) + string(mi3had) + /*" objetos -- rescate en "*/ STR(5858) + fn + /*".rescue"*/ STR(5856) });
				if (string_contains(filename_ext(fn), /*"backup"*/ STR(258)) || sBool(mi3_headless_active))
				{
					sReal(mi3_save_guard_blocked) = true;
					log({ /*"MI3 save guard"*/ STR(2959), /*"guardado ABORTADO (autosave/backup/headless)"*/ STR(5859) });
					if (!sBool(mi3_headless_active))
						toast_new(self, e_toast_NEGATIVE, text_get({ /*"saveguardempty"*/ STR(5860) }));
					return IntType(0);
				}
				if (!question(text_get({ /*"saveguardempty"*/ STR(5860) })))
				{
					sReal(mi3_save_guard_blocked) = true;
					log({ /*"MI3 save guard"*/ STR(2959), /*"guardado ABORTADO por el usuario"*/ STR(5861) });
					return IntType(0);
				}
				log({ /*"MI3 save guard"*/ STR(2959), /*"el usuario confirmo sobrescribir con un proyecto vacio"*/ STR(5862) });
			}
		}
		global::save_folder = sStr(project_folder);
		global::load_folder = sStr(project_folder);
		log({ /*"save_folder"*/ STR(896), global::save_folder });
		log({ /*"load_folder"*/ STR(897), global::load_folder });
		debug_timer_start();
		project_save_start(fn, true);
		project_save_project(self);
		project_save_render(self);
		project_save_background(self);
		project_save_objects(self);
		project_save_markers(self);
		project_save_done();
		debug_timer_stop(/*"project_save"*/ STR(5863));
		log({ /*"Project saved"*/ STR(5864) });
		if (!string_contains(filename_ext(fn), /*"backup"*/ STR(258)) && !global::mi3_cp_saving)
		{
			sInt(project_changed) = false;
			sBool(recent_add_wait) = true;
			session_update(self);
		}
		if (global::_app->window_state == /*"startup"*/ STR(138))
			project_reset(self);
		return 0.0;
	}
	
