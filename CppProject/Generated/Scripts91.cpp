	RealType tl_update_values_ease(ScopeAny self, IntType vid)
	{
		if (RenderLlmEvaluateChannel(self->id, vid)) return 0;
		VarType oldval, curval, nextval, val;
		oldval = sVar(value).Value(vid);
		if (sBool(keyframe_animate))
		{
			curval = sVar(keyframe_current_values).Value(vid);
			nextval = sVar(keyframe_next_values).Value(vid);
			if ((oldval == curval) && (oldval == nextval))
				return IntType(0);
			if (sBool(keyframe_smooth) && curval != nextval && tl_value_is_smoothable(vid))
				val = catmull_rom(sVar(keyframe_prev_values_cr).Value(vid), curval, nextval, sVar(keyframe_next2_values_cr).Value(vid), sReal(keyframe_progress));
			else
				val = tl_value_interpolate(vid, sVar(keyframe_progress_ease), curval, nextval);
			
		}
		else
			if (sInt(keyframe_next) > 0)
				val = sVar(keyframe_next_values).Value(vid);
			else
				val = sArr(value_default).Value(vid);
		
		
		if (oldval != val)
		{
			sBool(update_matrix) = true;
			sVar(value)[vid] = val;
		}
		return 0.0;
	}
	
	RealType tl_update_values_progress(ScopeAny self, VarType markerpos)
	{
		RealType kflength, kfprogress;
		RealType progress = IntType(0);
		if (!(global::_app->timeline_seamless_repeat > 0))
		{
			if (sInt(keyframe_current) > 0 && sInt(keyframe_next) > 0 && sInt(keyframe_current) != sInt(keyframe_next))
			{
				kflength = (markerpos - ObjType(obj_keyframe, sInt(keyframe_current))->position);
				kfprogress = (ObjType(obj_keyframe, sInt(keyframe_next))->position - ObjType(obj_keyframe, sInt(keyframe_current))->position);
				progress = kflength / kfprogress;
			}
			return progress;
		}
		VarType loopstart, loopend;
		BoolType seamlessloop;
		if (global::_app->timeline_region_start != null_)
		{
			loopstart = global::_app->timeline_region_start;
			loopend = global::_app->timeline_region_end;
		}
		else
		{
			loopstart = IntType(0);
			loopend = global::_app->timeline_length;
		}
		
		seamlessloop = (global::_app->timeline_seamless_repeat > 0 && markerpos >= loopstart && markerpos < loopend);
		IntType kflistsize;
		RealType lastkf;
		BoolType loopnext, loopprev;
		kflistsize = ds_list_size(sInt(keyframe_list));
		lastkf = kflistsize - IntType(1);
		loopnext = false;
		loopprev = false;
		if (sInt(keyframe_next) == sInt(keyframe_current) || ObjType(obj_keyframe, sInt(keyframe_next))->position > loopend)
		{
			for (IntType k = IntType(0); k < kflistsize; k++)
			{
				IntType kf = DsList(sInt(keyframe_list)).Value(k);
				if (ObjType(obj_keyframe, kf)->position < loopstart || ObjType(obj_keyframe, kf)->position > loopend)
					continue;
				else
				{
					if (ObjType(obj_keyframe, kf)->position < ObjType(obj_keyframe, sInt(keyframe_next))->position)
						sInt(keyframe_next) = kf;
				}
				
			}
			loopnext = true;
		}
		else
			if (sInt(keyframe_current) == null_ || ObjType(obj_keyframe, sInt(keyframe_current))->position < loopstart)
			{
				for (IntType k = IntType(0); k < kflistsize; k++)
				{
					IntType kf = DsList(sInt(keyframe_list)).Value(k);
					if (ObjType(obj_keyframe, kf)->position < loopstart || ObjType(obj_keyframe, kf)->position > loopend)
						continue;
					else
					{
						if (sInt(keyframe_current) == null_ || ObjType(obj_keyframe, kf)->position > ObjType(obj_keyframe, sInt(keyframe_current))->position)
							sInt(keyframe_current) = kf;
					}
					
				}
				loopprev = true;
			}
		
		RealType regionsize = loopend - loopstart;
		if (sInt(keyframe_current) > 0 && sInt(keyframe_next) > 0 && sInt(keyframe_current) != sInt(keyframe_next))
		{
			RealType range = ObjType(obj_keyframe, sInt(keyframe_next))->position - ObjType(obj_keyframe, sInt(keyframe_current))->position;
			if (loopnext)
				range += regionsize;
			else
				if (loopprev)
				{
					markerpos += regionsize;
					range += regionsize;
				}
			
			if (range != IntType(0))
				progress = (markerpos - ObjType(obj_keyframe, sInt(keyframe_current))->position) / range;
		}
		else
			sInt(keyframe_current) = sInt(keyframe_next);
		
		return progress;
	}
	
