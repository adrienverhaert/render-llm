	VarType tl_bounds_local(VarType tl)
	{
		VarType tp = idVar(tl, type);
		VarType tmp = idVar(tl, temp);
		switch ((IntType)tp)
		{
			case e_tl_type_BODYPART:
			{
				if (idVar(tl, model_part) == null_)
					return null_;
				VecType bs = idVec(idVar(tl, model_part), bounds_start);
				VecType be = idVec(idVar(tl, model_part), bounds_end);
				if (bs.Real(X_) > be.Real(X_) || bs.Real(Y_) > be.Real(Y_) || bs.Real(Z_) > be.Real(Z_))
					return null_;
				return ArrType::From({ bs.Real(X_), bs.Real(Y_), bs.Real(Z_), be.Real(X_), be.Real(Y_), be.Real(Z_) });
			}
			
			case e_tl_type_SCENERY:
			{
				if (tmp == null_ || idVar(tmp, scenery) == null_ || !idBool(idVar(tmp, scenery), ready))
					return null_;
				VecType sz = idVec(idVar(tmp, scenery), scenery_size);
				VarType rp = ((idVar(tmp, block_repeat_enable) > 0) ? idVar(tmp, block_repeat) : VarType(vec3(IntType(1))));
				if (sz.Real(X_) <= IntType(0) || sz.Real(Y_) <= IntType(0) || sz.Real(Z_) <= IntType(0))
					return null_;
				return ArrType::From({ IntType(0), IntType(0), IntType(0), rp.Value(X_) * sz.Real(X_) * block_size_, rp.Value(Y_) * sz.Real(Y_) * block_size_, rp.Value(Z_) * sz.Real(Z_) * block_size_ });
			}
			
			case e_tl_type_BLOCK:
			{
				if (tmp == null_)
					return null_;
				VarType rp = ((idVar(tmp, block_repeat_enable) > 0) ? idVar(tmp, block_repeat) : VarType(vec3(IntType(1))));
				return ArrType::From({ IntType(0), IntType(0), IntType(0), rp.Value(X_) * block_size_, rp.Value(Y_) * block_size_, rp.Value(Z_) * block_size_ });
			}
			
			case e_tl_type_MODEL:
			{
				if (tmp == null_ || idVar(tmp, model) == null_)
					return null_;
				if (idInt(idVar(tmp, model), model_format) != e_model_format_BLOCK)
					return null_;
				return ArrType::From({ IntType(0), IntType(0), IntType(0), block_size_, block_size_, block_size_ });
			}
			
			case e_tl_type_ITEM:
			{
				if (tmp == null_)
					return null_;
				return ArrType::From({ IntType(0), IntType(0), IntType(0), item_size, bool_to_float(idVar(tmp, item_3d)), item_size });
			}
			
			case e_tl_type_TEXT:
			{
				VecType tbs = idVec(tl, text_bounds_start);
				VecType tbe = idVec(tl, text_bounds_end);
				if (tbs.Real(X_) >= tbe.Real(X_) && tbs.Real(Z_) >= tbe.Real(Z_))
					return null_;
				return ArrType::From({ tbs.Real(X_), tbs.Real(Y_), tbs.Real(Z_), tbe.Real(X_), tbe.Real(Y_), tbe.Real(Z_) });
			}
			
			case e_tl_type_CUBE:
			case e_tl_type_CONE:
			case e_tl_type_CYLINDER:
			case e_tl_type_SPHERE:
			case e_tl_type_SURFACE:
			{
				return ArrType::From({ -IntType(8), -IntType(8), -IntType(8), IntType(8), IntType(8), IntType(8) });
			}
		}
		
		return null_;
	}
	
	VarType tl_bounds_world(VarType tl)
	{
		if (!idBool(tl, bounds_world_dirty))
		{
			if (idBool(tl, bounds_world_valid))
				return ArrType::From({ idVec(tl, bounds_world_min).Real(X_), idVec(tl, bounds_world_min).Real(Y_), idVec(tl, bounds_world_min).Real(Z_), idVec(tl, bounds_world_max).Real(X_), idVec(tl, bounds_world_max).Real(Y_), idVec(tl, bounds_world_max).Real(Z_) });
			else
				return null_;
			
		}
		idBool(tl, bounds_world_dirty) = false;
		idBool(tl, bounds_world_valid) = false;
		VarType lb = tl_bounds_local(tl);
		if (lb == null_)
			return null_;
		MatrixType mat = idMat(tl, matrix_render);
		VecType minv = ArrType::From({ no_limit, no_limit, no_limit });
		VecType maxv = ArrType::From({ -no_limit, -no_limit, -no_limit });
		for (IntType c = IntType(0); c < IntType(8); c++)
		{
			RealType cx = (((IntType)c & (IntType)IntType(1)) ? lb.Value(IntType(3)) : lb.Value(IntType(0)));
			RealType cy = (((IntType)c & (IntType)IntType(2)) ? lb.Value(IntType(4)) : lb.Value(IntType(1)));
			RealType cz = (((IntType)c & (IntType)IntType(4)) ? lb.Value(IntType(5)) : lb.Value(IntType(2)));
			VecType wp = point3D_mul_matrix(ArrType::From({ cx, cy, cz }), mat);
			for (IntType a = X_; a <= Z_; a++)
			{
				if (wp.Real(a) < minv.Real(a))
					minv.Real(a) = wp.Real(a);
				if (wp.Real(a) > maxv.Real(a))
					maxv.Real(a) = wp.Real(a);
			}
		}
		idVec(tl, bounds_world_min) = minv;
		idVec(tl, bounds_world_max) = maxv;
		idBool(tl, bounds_world_valid) = true;
		return ArrType::From({ minv.Real(X_), minv.Real(Y_), minv.Real(Z_), maxv.Real(X_), maxv.Real(Y_), maxv.Real(Z_) });
	}
	
	VarType tl_bounds_world_tree(VarType tl)
	{
		global::_app->mi3_gizmo_bounds_nodes = IntType(0);
		return tl_bounds_world_tree_acc(tl, null_);
	}
	
	VarType tl_bounds_world_tree_acc(VarType tl, VarType acc)
	{
		if (idBool(tl, render_visible))
		{
			VarType b = tl_bounds_world(tl);
			if (b != null_)
			{
				global::_app->mi3_gizmo_bounds_nodes++;
				if (acc == null_)
					acc = b;
				else
				{
					for (IntType a = IntType(0); a < IntType(3); a++)
					{
						if (b.Value(a) < acc.Value(a))
							acc[a] = b.Value(a);
						if (b.Value(a + IntType(3)) > acc.Value(a + IntType(3)))
							acc[a + IntType(3)] = b.Value(a + IntType(3));
					}
				}
				
			}
		}
		for (IntType i = IntType(0); i < ds_list_size(idInt(tl, tree_list)); i++)
			acc = tl_bounds_world_tree_acc(DsList(idInt(tl, tree_list)).Value(i), acc);
		return acc;
	}
	
