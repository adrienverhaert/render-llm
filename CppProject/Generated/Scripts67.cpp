				ObjType(obj_recent, recentobj)->last_opened = value_get_real(DsMap(projectmap).Value(/*"last_opened"*/ STR(3590)), -IntType(1));
				ObjType(obj_recent, recentobj)->pinned = value_get_real(DsMap(projectmap).Value(/*"pinned"*/ STR(5870)), false);
