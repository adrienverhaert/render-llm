				self->pattern_sprites = ArrType();
				self->res_ratio = ceil((RealType)sprite_get_width((IntType)(DsMap(idInt(res, model_texture_map)).Value(/*"entity/banner_base"*/ STR(5118)))) / sprite_get_width((IntType)(DsMap(ObjType(obj_resource, global::mc_res)->model_texture_map).Value(/*"entity/banner_base"*/ STR(5118)))));
