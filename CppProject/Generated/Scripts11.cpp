	void action_tl_frame_cam_ortho(ScopeAny self, BoolType enable)
	{
		RealType mi3sc = -IntType(1);
		if (enable && global::tl_edit != null_ && !(idVar(global::tl_edit, value).Value(e_value_CAM_ORTHO) > 0) && abs(idVar(global::tl_edit, value).Value(e_value_CAM_ORTHO_SCALE) - tl_value_default(e_value_CAM_ORTHO_SCALE)) < 0.0001)
			mi3sc = camera_ortho_frame_scale(self, global::tl_edit);
		tl_value_set_start(self, ID_action_tl_frame_cam_ortho, false);
		tl_value_set(self, { e_value_CAM_ORTHO, enable, false });
		if (mi3sc > IntType(0))
			tl_value_set(self, { e_value_CAM_ORTHO_SCALE, mi3sc, false });
		tl_value_set_done();
	}
	
	RealType camera_ortho_frame_scale(ScopeAny self, VarType tl)
	{
		if (tl == null_)
			return -IntType(1);
		if (idVar(tl, type) != e_tl_type_CAMERA)
			return -IntType(1);
		VarType mi3aw, mi3ah;
		if (idVar(tl, value).Value(e_value_CAM_SIZE_USE_PROJECT) > 0)
		{
			mi3aw = sVar(project_video_width);
			mi3ah = sVar(project_video_height);
		}
		else
		{
			mi3aw = idVar(tl, value).Value(e_value_CAM_WIDTH);
			mi3ah = idVar(tl, value).Value(e_value_CAM_HEIGHT);
		}
		
		RealType mi3asp = max({ 0.0001, (RealType)mi3aw / max({ IntType(1), mi3ah }) });
		VarType mi3fov = max({ IntType(1), idVar(tl, value).Value(e_value_CAM_FOV) });
		VarType mi3d = -IntType(1);
		RealType mi3pw = IntType(128);
		RealType mi3ph = max({ IntType(1), round(128.0 / mi3asp) });
		VarType mi3psurf = surface_require(-IntType(1), mi3pw, mi3ph);
		if (surface_exists((IntType)(mi3psurf)))
		{
			VarType mi3ptarget = global::render_target;
			VarType mi3pcam = global::render_camera;
			render_start(self, { mi3psurf, null_, mi3pw, mi3ph });
			global::render_camera = tl;
			render_update_camera(self);
			global::cam_ortho = false;
			surface_set_target((IntType)(mi3psurf));
		{
			draw_clear_alpha(c_black, 0.0);
			render_world_start();
			render_world(self, e_render_mode_COLOR_FOG);
			render_world_done();
		}
			surface_reset_target();
			render_done();
			gpu_set_blendmode(bm_normal);
			surface_clear_depth_cache(mi3psurf);
			IntType mi3n = IntType(0);
			ArrType mi3samp = array_create({ IntType(9), IntType(1) });
			IntType mi3i, mi3j, mi3k;
			RealType mi3dv;
			for (mi3j = IntType(0); mi3j < IntType(3); mi3j++)
				for (mi3i = IntType(0); mi3i < IntType(3); mi3i++)
				{
					mi3dv = surface_get_depth(mi3psurf, round(mi3pw * (0.375 + 0.125 * mi3i)), round(mi3ph * (0.375 + 0.125 * mi3j)));
					if (mi3dv >= IntType(1))
						continue;
					mi3k = mi3n;
					while (mi3k > IntType(0) && mi3samp.Value(mi3k - IntType(1)) > mi3dv)
					{
						mi3samp[mi3k] = mi3samp.Value(mi3k - IntType(1));
						mi3k--;
					}
					
					mi3samp[mi3k] = mi3dv;
					mi3n++;
				}
			if (mi3n > IntType(0))
			{
				VecType mi3clip = vec4(IntType(0), IntType(0), min({ 0.99975, mi3samp.Value((IntType)(mi3n / IntType(2))) }) * IntType(2) - IntType(1), IntType(1));
				VecType mi3view = vec4_homogenize(vec4_mul_matrix(mi3clip, matrix_inverse(global::proj_matrix)));
				VecType mi3world = point3D_mul_matrix(mi3view, matrix_inverse(global::view_matrix));
				mi3d = point3D_distance(global::cam_from, mi3world);
			}
			log({ /*"ortho autoscale"*/ STR(145), /*"sonda "*/ STR(146) + string(mi3pw) + /*"x"*/ STR(147) + string(mi3ph) + /*": "*/ STR(148) + string(mi3n) + /*"/9 muestras con geometria -> d="*/ STR(149) + string(mi3d) });
			surface_free((IntType)(mi3psurf));
			global::render_target = mi3ptarget;
			global::render_camera = mi3pcam;
		}
		if (mi3d <= IntType(0) && idVar(tl, value).Value(e_value_CAM_ROTATE) > 0)
			mi3d = idVar(tl, value).Value(e_value_CAM_ROTATE_DISTANCE);
		if (mi3d <= IntType(0) && idVar(tl, value).Value(e_value_CAM_DOF) > 0 && idVar(tl, value).Value(e_value_CAM_DOF_DEPTH) > IntType(0))
			mi3d = idVar(tl, value).Value(e_value_CAM_DOF_DEPTH);
		if (mi3d <= IntType(0) || mi3d >= no_limit)
		{
			log({ /*"ortho autoscale"*/ STR(145), /*"sin medida fiable -> se conserva el default"*/ STR(150) });
			return -IntType(1);
		}
		RealType mi3sc = IntType(2) * mi3d * mi3asp * (dsin((RealType)mi3fov / 2.0) / dcos((RealType)mi3fov / 2.0));
		log({ /*"ortho autoscale"*/ STR(145), /*"d="*/ STR(151) + string(mi3d) + /*" fov="*/ STR(152) + string(mi3fov) + /*" aspect="*/ STR(153) + string(mi3asp) + /*" -> scale="*/ STR(154) + string(mi3sc) });
		return mi3sc;
	}
	
