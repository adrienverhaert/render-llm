	RealType project_load(ScopeAny self, VarArgs argument)
	{
		IntType argument_count = argument.Size();
		VarType fn = (argument_count > IntType(0) ? argument[IntType(0)] : file_dialog_open_project(self));
		if (fn == /*""*/ STR(0))
			return IntType(0);
		VarType name = filename_new_ext(filename_name(fn), /*""*/ STR(0));
		if (filename_ext(fn) == /*".zip"*/ STR(63))
		{
			unzip(fn);
			fn = file_find_single(unzip_directory, /*".miproject;.mproj;.mani"*/ STR(5499));
			if (!file_exists_lib(fn))
				fn = file_find_single(unzip_directory + name + /*"/"*/ STR(41), /*".miproject;.mproj;.mani"*/ STR(5499));
			if (!file_exists_lib(fn))
			{
				error(/*"erroropenprojectzip"*/ STR(5500));
				return IntType(0);
			}
		}
		if (!file_exists_lib(fn))
			return IntType(0);
		StringType ext;
		IntType rootmap, buf;
		BoolType legacy;
		ext = filename_ext(fn);
		if (ext == /*".miproject"*/ STR(864) || string_contains(ext, /*".backup"*/ STR(5491)))
		{
			log({ /*"Opening project"*/ STR(5501), fn });
			rootmap = project_load_start(fn);
			if (rootmap == null_)
				return IntType(0);
			legacy = false;
		}
		else
		{
			log({ /*"Opening legacy project"*/ STR(5502), fn });
			if (!project_load_legacy_start(fn))
				return IntType(0);
			buf = global::buffer_current;
			legacy = true;
		}
		
		project_reset(self);
		project_reset_loaded(self);
		sVar(project_file) = filename_new_ext(fn, /*".miproject"*/ STR(864));
		sStr(project_folder) = filename_dir(fn);
		sVar(project_name) = name;
		global::save_folder = sStr(project_folder);
		global::load_folder = filename_dir(fn);
		log({ /*"save_folder"*/ STR(896), global::save_folder });
		log({ /*"load_folder"*/ STR(897), global::load_folder });
		missing_res_start();
		if (!legacy)
		{
			project_load_project(self, DsMap(rootmap).Value(/*"project"*/ STR(363)));
			project_load_render(self, DsMap(rootmap).Value(/*"render"*/ STR(124)));
			if (is_string(sVar(project_render_settings)) && sVar(project_render_settings) != /*""*/ STR(0) && file_exists_lib(render_directory + sVar(project_render_settings) + /*".mirender"*/ STR(128)))
			{
				IntType mi3pmap = json_load({ render_directory + sVar(project_render_settings) + /*".mirender"*/ STR(128) });
				if (ds_map_valid(mi3pmap))
				{
					project_load_render(self, DsMap(mi3pmap).Value(/*"render"*/ STR(124)));
					ds_map_destroy(mi3pmap);
					log({ /*"Preset re-imported"*/ STR(5503), sVar(project_render_settings) });
				}
			}
			project_load_background(self, DsMap(rootmap).Value(/*"background"*/ STR(369)));
			project_load_objects(rootmap);
			project_load_markers(DsMap(rootmap).Value(/*"markers"*/ STR(5504)));
		}
		else
		{
			global::buffer_current = buf;
			if (global::load_format >= e_project_FORMAT_100_DEMO_2)
			{
				project_load_legacy_project(self);
				project_load_legacy_objects();
				project_load_legacy_background(self);
				project_load_legacy_work_camera(self);
			}
			else
				project_load_legacy_beta(self, true);
			
			buffer_delete(global::buffer_current);
		}
		
		project_load_find_save_ids(self);
		project_load_update(self);
		project_reset_loaded(self);
		log({ /*"Project loaded"*/ STR(5505) });
		missing_res_report();
		session_update(self);
		if (global::load_format < e_project_FORMAT_110_PRE_1)
		{
			if (!dev_mode)
				file_rename_lib(fn, fn + /*".old"*/ STR(5506));
			project_save(self);
		}
		sBool(recent_add_wait) = true;
		mi3_checkpoint_session_reset();
		global::mi3_cp_picker_wait = !global::mi3_cp_restoring;
		global::mi3_cp_picker_agent = global::mi3_as_live_exec;
		return true;
	}
	
